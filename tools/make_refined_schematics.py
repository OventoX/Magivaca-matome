def test_matching():
    with open("tools/chests_extracted.json", "r", encoding="utf-8") as fp:
        chests = json.load(fp)
    schematics = get_refined_schematics()
    print(f"Checking matching for {len(schematics)} areas...")
    
    total_schematic_chests = 0
    all_matched = True
    for area, defn in schematics.items():
        area_chests = [c for c in chests if c.get("area") == area]
        total_schematic_chests += len(area_chests)
        grid = defn["grid"]
        
        # Collect all aliases in nodes
        alias_map = {}
        for r in grid:
            for node in r:
                if node:
                    for a in node["aliases"]:
                        alias_map[a] = node["name"]
                        
        for c in area_chests:
            m = c["mapName"]
            if m not in alias_map:
                print(f"[ERROR] {area}: Chest {c['id']} ({c['item']}) with mapName '{m}' is not mapped to any node!")
                all_matched = False
                
    if all_matched:
        print(f"SUCCESS! All {total_schematic_chests} chests across 32 schematic areas matched 100% perfectly!")
        with open("tools/refined_schematics.json", "w", encoding="utf-8") as fp:
            json.dump(schematics, fp, ensure_ascii=False, indent=2)

if __name__ == "__main__":
    test_matching()
